import assert from 'node:assert/strict';
import { createKilnPerformance, defaultKilnCues, sampleKilnKeys } from '../kiln-cinematic-cues.mjs';
const cues = defaultKilnCues();
assert.equal(defaultKilnCues({inputRadius:0.08}).work[1].radius, 0.08, 'default pulse respects the emitter minimum');
assert.equal(sampleKilnKeys([{time:0,radius:0.1,flow:0},{time:2,radius:0.5,flow:2}], 1).flow, 1);
let time = 0;
const run = createKilnPerformance(cues, {now: () => time});
run.start('live');
assert.equal(run.sample().sourceEnabled, false);
time = 2;
assert.equal(run.sample().phase, 'ignition');
time = 10000;
assert.equal(run.sample().phase, 'work', 'elapsed time never fabricates inference completion');
assert.equal(run.sample().outputVisible, false);
assert.throws(() => run.complete({status:'pending',objectId:'chair'}), /registered/);
run.complete({status:'registered', objectId:'chair'});
assert.equal(run.sample().sourceEnabled, false);
assert.equal(run.sample().phase, 'extinguish');
assert.equal(run.sample().outputVisible, false);
time += cues.extinguishSeconds;
assert.equal(run.sample().phase, 'reveal');
assert.equal(run.sample().outputVisible, true);
time += cues.revealSeconds;
assert.equal(run.sample().phase, 'complete');
assert.equal(run.sample().sourceEnabled, false);
assert.equal(run.sample().light, 1);
const failed = createKilnPerformance(cues, {now: () => time});
failed.start('live'); failed.fail('GPU lost');
assert.equal(failed.sample().phase, 'failed');
assert.equal(failed.sample().outputVisible, false);
assert.equal(failed.sample().sourceEnabled, false);
assert.throws(() => failed.complete({status:'registered',objectId:'chair'}), /cannot complete/);
console.log('Cinematic interpolation and truthful reveal contracts passed');
