// kaminos-test: node
import assert from 'node:assert/strict';
import {createWorkpieceAuthoring,initialWorkpieces,stairPlan,troughPlan,cornerPlan,WORKPIECES,interpretWorkpiece} from '../stockroom-workpiece-state.mjs';
import {createWorkpieceView} from '../stockroom-workpiece-view.mjs';
const author=createWorkpieceAuthoring(),initial=initialWorkpieces();
assert.doesNotThrow(()=>author.begin('stairs'),'Attached stairs must be independently actionable, rather than renamed bridge geometry');
assert.equal(author.read().stage,'shaping');
author.shape({u:1,v:2.7});author.hold();
assert.deepEqual(author.read().models,initial,'Holding a situation cannot commit it');
assert.deepEqual(author.display().stairs,{kind:'rebuild',u:1,v:2.7},'Held situation stays visible before any choice is hovered');
author.highlight('swing');const swing=author.display().stairs;
author.highlight('rebuild');const rebuilt=author.display().stairs;
assert.equal(stairPlan(swing).run,2.2,'Rigid flight retains its length');
assert.ok(stairPlan(rebuilt).run>2.8,'Rebuilt flight changes member length');
assert.deepEqual(stairPlan(swing).top,stairPlan(rebuilt).top,'Both retain the upper relationship');
assert.deepEqual(interpretWorkpiece('stairs','swing',{kind:'swing',u:.3,v:.2}),{kind:'swing',u:.3,v:.2},'Reentering a chosen interpretation retains its parameters');
author.choose();author.tune({u:1.5,v:3});const tuned=author.read();author.enter();
assert.equal(author.read().stage,'idle');assert.equal(author.read().models.stairs.u,1.5);
author.back();assert.deepEqual(author.read(),tuned,'Back from the result recovers exact tuning');
author.back();assert.equal(author.read().stage,'choosing');assert.deepEqual(author.read().intent,{kind:'rebuild',u:1,v:2.7});
author.back();assert.equal(author.read().stage,'shaping');author.back();assert.deepEqual(author.read().models,initial);
assert.throws(()=>author.shape({u:1}),/Expected shaping/);
author.begin('trough');author.shape({u:.2,v:.5});author.hold();
author.highlight('branch');const branch=troughPlan(author.display().trough);
author.highlight('carry');const carry=troughPlan(author.display().trough);
author.highlight('route');const route=troughPlan(author.display().trough);
assert.deepEqual(branch.left,[-1.45,.85,-1.45]);assert.notDeepEqual(carry.left,branch.left);
assert.deepEqual(branch.inlet,carry.inlet);assert.deepEqual(route.left,branch.left);
assert.equal(branch.routes[2].length,2);assert.equal(route.routes[2].length,13);
assert.ok(route.right[1]>.85);
author.reset();author.begin('corner');author.shape({u:.5,v:.2});author.hold();
author.highlight('carry');const carryCorner=cornerPlan(author.display().corner);
author.highlight('leave');const leaveCorner=cornerPlan(author.display().corner);
author.highlight('wrap');const wrapCorner=cornerPlan(author.display().corner);
assert.notDeepEqual(carryCorner.returnTop,leaveCorner.returnTop);assert.deepEqual(leaveCorner.returnTop,[1.15,1.95,0]);
assert.equal(wrapCorner.band,.6);assert.deepEqual(carryCorner.canopy,wrapCorner.canopy);
const before=author.read();assert.throws(()=>author.highlight('swing'),/Unknown construction/);assert.deepEqual(author.read(),before);
author.choose();const beforeBad=author.read();assert.throws(()=>author.tune({u:NaN}),/Parameters/);assert.deepEqual(author.read(),beforeBad);
author.enter();author.begin('stairs');assert.equal(author.read().piece,'stairs','Other workpieces remain accessible after entering');
const view=createWorkpieceView();
for(const id of Object.keys(WORKPIECES))assert.ok(view.targets().some(m=>m.userData.workpiece===id));
view.update({stairs:rebuilt,trough:{kind:'carry',u:.2,v:.5},corner:{kind:'wrap',u:.5,v:.6}},'corner');
assert.deepEqual(view.plans().trough,carry);assert.equal(view.plans().corner.band,.6);
const meshes=[];view.root.traverse(m=>{if(m.isMesh)meshes.push(m);});
view.update(initial);
const again=[];view.root.traverse(m=>{if(m.isMesh)again.push(m);});
assert.equal(meshes.length,again.length,'Pointer updates reuse mesh resources rather than rebuilding the scene');
view.update({...initial,trough:{kind:'route',u:2,v:.8}});
const swept=view.targets().find(m=>m.userData.channelRoute===2);
assert.equal(swept.geometry.drawRange.count,12*8*6,'Route uses connected section rings rather than separate rigid tiles');
assert.equal(swept.geometry.attributes.position.count,13*8);
view.update(initial);assert.equal(swept.geometry.drawRange.count,8*6,'A later straight route hides unused curved capacity');
console.log('Workpiece decisions, retained relationships, backtracking, invalid-input retention and view reuse pass');
