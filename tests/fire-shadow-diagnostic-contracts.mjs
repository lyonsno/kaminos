import assert from 'node:assert/strict';
import {createFireLightFieldShadow} from '../fire-light-field-shadow.mjs';
import * as THREE from '../lib/three.webgpu.js';
import {rayEvidence} from '../fire-shadow-diagnostic.mjs';
const {vec3}=THREE.TSL;
const pass=createFireLightFieldShadow({renderer:{},scene:{},sourceNode:vec3(0),receiverNode:vec3(0),normalNode:vec3(0,1,0)});
assert.equal(typeof pass.diagnose,'function','shadow diagnostic must expose the actual production comparison, not a separate approximation');
await assert.rejects(()=>pass.diagnose([{x:0,y:0}]),/shadow-not-effective/,'disabled or unrendered shadow maps cannot be diagnostic evidence');
pass.dispose();
const scene=new THREE.Scene(),material=new THREE.MeshBasicMaterial({side:THREE.DoubleSide});
const plane=new THREE.Mesh(new THREE.PlaneGeometry(4,4),material);plane.rotation.x=-Math.PI/2;plane.castShadow=true;scene.add(plane);scene.updateMatrixWorld(true);
const unblocked=rayEvidence(scene,[0,1,0],[.2,0,.1]);
assert.ok(Math.abs(unblocked.hits[0].distance-unblocked.distance)<1e-6);
assert.equal(unblocked.hits[0].triangle.length,3);
const blocker=plane.clone();blocker.position.y=.5;scene.add(blocker);scene.updateMatrixWorld(true);
const blocked=rayEvidence(scene,[0,1,0],[.2,0,.1]);
assert.ok(Math.abs(blocked.hits[0].distance-blocked.distance*.5)<1e-6);
blocker.castShadow=false;
assert.ok(Math.abs(rayEvidence(scene,[0,1,0],[.2,0,.1]).hits[0].distance-unblocked.distance)<1e-6);
console.log('shadow diagnostic refuses unavailable live evidence');
