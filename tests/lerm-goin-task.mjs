// kaminos-test: node
import assert from 'node:assert/strict';
import {createGoinTask} from '../experiments/lerms/goin-task.mjs';
let target={id:'goin-a',position:[2,0,0]};
const task=createGoinTask({target:()=>target,arrivalRadius:.2});
const step=(time,position=[0,0,0])=>task.update({time,position});
assert.deepEqual(step(0),{source:'lerms.goin-task.v1',destination:[2,0,0],hold:false,motionStart:0});
step(300);assert.equal(task.read().phase,'approaching','Task must not expire like curiosity');
target.position=[-2,0,1];assert.deepEqual(step(301).destination,[-2,0,1]);
assert.equal(step(302,[-2,0,1]).hold,true);assert.equal(task.read().phase,'at-goin');
target.position=[2,0,1];assert.equal(step(303,[-2,0,1]).hold,false);
task.interrupt({id:'hit-1',source:'manual-test',time:303,seconds:2});assert.equal(step(304).hold,true);
task.interrupt({id:'hit-1',source:'manual-test',time:303,seconds:200});assert.equal(step(305).hold,false,'Duplicate contact must not restart interruption');
assert.equal(task.read().target,'goin-a','Interruption must preserve task identity');
target=null;assert.deepEqual(step(306),{source:'lerms.goin-task.v1',destination:null,hold:true,motionStart:305});
assert.equal(task.read().phase,'waiting-target');
target={id:'goin-a',position:[1,0,0]};assert.equal(step(307).hold,false);
target.position=[Infinity,0,0];assert.throws(()=>step(308),/observation/);
assert.throws(()=>step(2),/monotonic/);assert.throws(()=>task.interrupt({seconds:2}),/event/);
assert.throws(()=>task.interrupt({id:'stale',source:'manual-test',time:2,seconds:1}),/monotonic/);
console.log('Persistent goin intent follows current target, holds at arrival, resumes after sourced interruption and stops on target loss');
let escape=[9,0,0],coin={id:'coin',position:[0,1,0]};
const theft=createGoinTask({target:()=>coin,arrivalRadius:.5,theft:{carrierId:'lerm',escape:()=>escape}});
const steal=theft.update({time:0,position:[0,0,0]});
assert.equal(theft.read().custody.phase,'carried');
assert.equal(theft.read().custody.carrierId,'lerm');
assert.deepEqual(steal.destination,escape);assert.equal(steal.hold,false);
escape=[-9,0,0];assert.deepEqual(theft.update({time:1,position:[1,0,0]}).destination,escape);
coin.position=[1,2,0];
theft.interrupt({id:'drop-1',source:'explicit-test-operation',time:1,seconds:1});
assert.equal(theft.read().custody.phase,'dropped');assert.equal(theft.read().custody.carrierId,null);
assert.deepEqual(theft.read().transition.position,[1,2,0]);assert.equal(theft.read().transition.goinId,'coin');
assert.equal(theft.read().transition.cause,'scripted_fixture');
assert.equal(theft.update({time:1.5,position:[1,0,0]}).hold,true);
assert.equal(theft.read().custody.phase,'dropped','A nearby dropped goin stays released throughout the interruption');
assert.equal(theft.update({time:2,position:[1,0,0]}).hold,false);
assert.equal(theft.read().custody.phase,'carried','The same goin can be stolen again after recovery');
const revision=theft.read().custody.revision;
theft.interrupt({id:'drop-1',source:'explicit-test-operation',time:1,seconds:100});
assert.equal(theft.read().custody.revision,revision,'A duplicate hit must not release a later claim');
coin=null;assert.equal(theft.update({time:3,position:[1,0,0]}).hold,true);
assert.equal(theft.read().phase,'waiting-target');
coin={id:'coin',position:[1,2,0]};
theft.interrupt({id:'water-1',source:'gpu-interface-sphere-overlap',cause:'juice_hit',time:3,seconds:1});
theft.setWaterExposure(true);theft.update({time:5,position:[1,0,0]});
assert.equal(theft.read().custody.phase,'dropped');assert.equal(theft.read().phase,'water-exposed','Continued exposure prevents a pickup loop');
assert.equal(theft.read().transition.cause,'juice_hit');
theft.setWaterExposure(false);theft.update({time:5,position:[1,0,0]});assert.equal(theft.read().custody.phase,'carried');
theft.setHeld({held:true,time:5});
assert.equal(theft.read().custody.carrierId,null,'Grabbing transfers possession without a hit');
assert.equal(theft.read().interruption.until,4,'Grabbing must not add an interruption cooldown');
coin.position=[-3,2,1];
assert.deepEqual(theft.update({time:6,position:[1,0,0]}).destination,coin.position);
assert.equal(theft.update({time:7,position:[-3,0,1]}).hold,true);
assert.equal(theft.read().custody.carrierId,null,'The creature cannot reclaim while the operator holds it');
assert.equal(theft.read().phase,'watching-held-goin');
theft.setHeld({held:false,time:7});
coin.claimable=false;theft.update({time:7,position:[-3,0,1]});
