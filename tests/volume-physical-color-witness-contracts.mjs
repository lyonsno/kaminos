import assert from 'node:assert/strict';
import { assertArmEquivalent } from '../volume-physical-color-witness-contract.mjs';
const contract = await import('../volume-physical-color-witness-contract.mjs');
assert.equal(typeof contract.assertWitnessCamera, 'function');
const camera={position:[3,2,7],target:[0,1,0]};
contract.assertWitnessCamera(camera,camera);
assert.throws(()=>contract.assertWitnessCamera(camera,{...camera,position:[0,0,0]}),/camera/);
assert.throws(()=>contract.assertWitnessCamera(camera,null),/camera/);
assert.equal(typeof contract.assertSharedSceneConsumers, 'function', 'shared-light witness must reject missing or stale consumers');
const shared={materialCount:1,frame:{frame:160,generation:3,hostDepthEffective:true,presented:true},shadow:{effective:true}};
contract.assertSharedSceneConsumers(shared,160);
assert.throws(()=>contract.assertSharedSceneConsumers({...shared,materialCount:0},160), /material/);
assert.throws(()=>contract.assertSharedSceneConsumers({...shared,frame:{...shared.frame,frame:159}},160), /stale/);
assert.throws(()=>contract.assertSharedSceneConsumers({...shared,frame:{...shared.frame,hostDepthEffective:false}},160), /depth/);
assert.throws(()=>contract.assertSharedSceneConsumers({...shared,frame:{...shared.frame,presented:false}},160), /presented/);
const {assertSceneSourceCapture} = await import('../volume-physical-color-witness-contract.mjs');
assert.equal(typeof assertSceneSourceCapture, 'function', 'raw source evidence must reject false completion');
const source = {kind:'coefficients', channels:4, dimensions:[1,2,1], frame:160, generation:1, values:[1,0,0,2,0,1,0,3]};
assertSceneSourceCapture(source,160);
assert.throws(()=>assertSceneSourceCapture({...source,frame:159},160), /frame/);
assert.throws(()=>assertSceneSourceCapture({...source,values:[1,0,0,2]},160), /partial/);
assert.throws(()=>assertSceneSourceCapture({...source,values:Array(8).fill(0)},160), /emission/);
assert.throws(()=>assertSceneSourceCapture({...source,values:[NaN,0,0,2,0,1,0,3]},160), /nonfinite/);
assert.throws(()=>assertSceneSourceCapture({...source,kind:'optical-depth'},160), /kind/);
const earlier = new Map([['bright',Buffer.from([3,5,8,255])]]);
assertArmEquivalent({id:'isolation',equalTo:'bright'},Buffer.from([3,5,8,255]),earlier);
assert.throws(()=>assertArmEquivalent({id:'isolation',equalTo:'bright'},Buffer.from([3,5,9,255]),earlier),/raw RGBA differs/);
assert.throws(()=>assertArmEquivalent({id:'isolation',equalTo:'missing'},Buffer.from([3,5,8,255]),earlier),/prior arm missing/);
assert.throws(()=>assertArmEquivalent({id:'isolation',equalTo:'bright'},Buffer.from([3,5,8]),earlier),/raw RGBA differs/);
assertArmEquivalent({id:'normal'},Buffer.from([1,2,3,255]),earlier);
console.log('named same-state raw-RGBA arm equivalence passes; altered/partial/missing-reference fail');
