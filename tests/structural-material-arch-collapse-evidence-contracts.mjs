import assert from 'node:assert/strict';
import fs from 'node:fs';
import { gunzipSync } from 'node:zlib';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import { inspectArchCollapseState } from '../structural-material-arch-collapse-evidence.mjs';

const evidence = 'artifacts/structural-material-3d/arch-gravity-collapse-2026-10-01/';
const observed = JSON.parse(gunzipSync(fs.readFileSync(`${evidence}assay-r2.json.gz`)));
const state = observed.cases[3].frames.at(-1).state;
assert.deepEqual(inspectArchCollapseState(state, { strength: 120, layers: 3 }).errors, []);
assert(inspectArchCollapseState({ ...state, backend: 'fallback' }).errors.includes('wrong effective physics route'));
assert(inspectArchCollapseState(state, { strength: 80 }).errors.includes('effective config mismatch: strength'));
assert(inspectArchCollapseState({ ...state, bodies: [] }).errors.includes('missing structural output'));
assert(inspectArchCollapseState({ ...state, time: 0 }).errors.includes('missing or inconsistent simulation time'));
assert(inspectArchCollapseState({ ...state, broken: 0 }).errors.includes('damage count disagrees with connections'));
const unstable = JSON.parse(gunzipSync(fs.readFileSync(`${evidence}assay-r1.json.gz`))).cases[1].frames.at(-1).state;
assert(inspectArchCollapseState(unstable).errors.includes('invalid floor containment'),
  'the actual rejected spring run must not masquerade as valid physics');
const invalidRotation = structuredClone(state); invalidRotation.bodies[0].quaternion.w = 2;
assert(inspectArchCollapseState(invalidRotation).errors.some(error => error.startsWith('invalid rotation')));
assert.deepEqual(inspectArchCollapseState({ ...state, futureField: true }).errors, [], 'unknown additive evidence remains compatible');
const output = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'arch-collapse-negative-')), 'failure.json');
const failed = spawnSync(process.execPath, ['structural-material-arch-collapse-smoke.mjs', 'http://127.0.0.1:18434/wrong-route.html', output, '/missing/browser'], { encoding: 'utf8' });
assert.equal(failed.status, 1);
const receipt = JSON.parse(fs.readFileSync(output));
assert.equal(receipt.status, 'failed'); assert.equal(receipt.phase, 'preflight');
assert.equal(receipt.effectiveUrl, null); assert.equal(Object.keys(receipt.captures).length, 0);
assert.match(receipt.error.message, /exact local collapse route/);
const fake = path.join(path.dirname(output), 'Chromium');
fs.writeFileSync(fake, '#!/bin/sh\nprintf "fake browser\\n"\n'); fs.chmodSync(fake, 0o755);
const fakeOutput = path.join(path.dirname(output), 'fake-executable.json');
const fakeRun = spawnSync(process.execPath, ['structural-material-arch-collapse-smoke.mjs', 'http://127.0.0.1:18434/structural-material-arch-collapse.html?smoke=1', fakeOutput, fake], { encoding: 'utf8' });
assert.equal(fakeRun.status, 1);
const fakeReceipt = JSON.parse(fs.readFileSync(fakeOutput));
assert.equal(fakeReceipt.phase, 'preflight', 'an executable-name match must not admit a launcher script');
assert.match(fakeReceipt.error.message, /native browser binary/);
const liveOutput = path.join(path.dirname(output), 'live-route-preflight.json');
spawnSync(process.execPath, ['structural-material-arch-collapse-smoke.mjs', 'http://127.0.0.1:18434/structural-material-arch-collapse.html', liveOutput, fake], { encoding: 'utf8' });
const liveReceipt = JSON.parse(fs.readFileSync(liveOutput));
assert.match(liveReceipt.error.message, /native browser binary/, 'the actual operator URL must reach browser admission, not be rejected as a wrong route');
console.log('arch collapse evidence contracts passed');
