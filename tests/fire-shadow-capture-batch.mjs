// kaminos-test: node
import assert from 'node:assert/strict';
import * as THREE from '../lib/three.webgpu.js';
import * as shadow from '../fire-light-field-shadow.mjs';
assert.equal(typeof shadow.renderFireShadowBatch,'function','source captures must share one current scene preparation');
const scene=new THREE.Scene(),mesh=new THREE.Mesh(new THREE.BoxGeometry(),new THREE.MeshStandardMaterial());
mesh.castShadow=true;scene.add(mesh);
let updates=0,walks=0;
const update=scene.updateMatrixWorld.bind(scene),walk=scene.traverseVisible.bind(scene);
scene.updateMatrixWorld=(...args)=>{updates++;return update(...args);};
scene.traverseVisible=fn=>{walks++;return walk(fn);};
const seen=[],captures=Array.from({length:4},()=>({render(frame){seen.push(frame);}}));
shadow.renderFireShadowBatch({scene,shadows:captures});
assert.equal(updates,1);assert.equal(walks,1);
assert.equal(seen.length,4);assert(seen.every(frame=>frame===seen[0]));
assert.equal(seen[0].scene,scene);assert.deepEqual(seen[0].casters,[mesh]);
assert.equal(seen[0].extent.length(),Math.sqrt(.75));
mesh.position.x=5;
shadow.renderFireShadowBatch({scene,shadows:captures});
assert.equal(updates,2);assert.equal(walks,2);
assert.notEqual(seen[4],seen[0],'each batch must prepare current geometry');
assert.equal(seen[4].extent.x,5.5);
mesh.visible=false;
shadow.renderFireShadowBatch({scene,shadows:captures});
assert.deepEqual(seen[8].casters,[]);
mesh.visible=true;mesh.material.transparent=true;
assert.throws(()=>shadow.renderFireShadowBatch({scene,shadows:captures}),/unsupported-caster/);
assert.equal(seen.length,12,'invalid caster must fail before any cube is rendered');
const real=shadow.createFireLightFieldShadow({renderer:{},scene,sourceNode:THREE.TSL.vec3(0),receiverNode:THREE.TSL.vec3(1),normalNode:THREE.TSL.vec3(0,1,0),requested:true});
assert.throws(()=>real.render(seen[0]),/inactive-or-foreign-batch/,'retaining a snapshot must not authorize a later capture');
mesh.material.transparent=false;
const foreignScene=new THREE.Scene();
assert.throws(()=>shadow.renderFireShadowBatch({scene:foreignScene,shadows:[real]}),/inactive-or-foreign-batch/);
let failedFrame;
assert.throws(()=>shadow.renderFireShadowBatch({scene,shadows:[{render(frame){failedFrame=frame;throw Error('capture failed');}}]}),/capture failed/);
assert.throws(()=>real.render(failedFrame),/inactive-or-foreign-batch/,'failed batches must also expire');
real.dispose();mesh.geometry.dispose();mesh.material.dispose();
let casterScopes=0;
shadow.renderFireShadowBatch({scene:new THREE.Scene(),shadows:[],casterScene:{withCapture(fn){casterScopes++;return fn();}}});
assert.equal(casterScopes,1,'one caster-only scene scope must enclose the complete fresh-cube batch');
console.log('PASS shared current capture preparation, visibility and support failure');
