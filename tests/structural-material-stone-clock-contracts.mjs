import assert from 'node:assert/strict';
import { stoneConsumerFixture } from './helpers/stone-consumer-fixture.mjs';

const f=await stoneConsumerFixture(), {api}=f;
const first=api.witness();
assert.ok(first.clock?.runId, 'Actual stone consumer must expose reset-scoped run identity');
assert.equal(first.clock.constructionSteps,30);
assert.equal(first.clock.completedSteps,30);
assert.equal(first.clock.submittedSteps,30);
assert.equal(first.clock.completedSeconds,.5,'Construction loading is physical time, not a zero-time start');
assert.equal(first.clock.experimentSeconds,0);
api.pull(.02);
await api.advance(3);
const held=await api.hold();
assert.equal(held.clock.runId,first.clock.runId);
assert.equal(held.clock.completedSteps,33);
assert.equal(held.clock.submittedSteps,33);
assert.equal(held.clock.presentedSteps,33);
assert.equal(held.clock.completedSeconds,.55);
assert.equal(held.clock.experimentSeconds,.05);
assert.equal(held.clock.paused,true);
assert.equal(held.clock.busy,false);
assert.equal(held.clock.presentationDrained,true);
assert(held.specimens.every(s=>s.state.hand),'Hold must preserve the applied injury load');
const physics=held.specimens.map(s=>structuredClone(s.state));
await api.camera({position:[5,3,7],target:[0,0,0],up:[0,1,0],fov:40,near:.02,far:90});
const inspected=await api.hold();
assert.notDeepEqual(inspected.camera,held.camera);
assert.deepEqual(inspected.specimens.map(s=>s.state),physics,'Camera inspection must not advance or rewrite material');
assert.equal(inspected.clock.completedSteps,33);
await assert.rejects(api.camera({position:[NaN,3,7],target:[0,0,0],up:[0,1,0]}),/Camera/);
assert.deepEqual(api.witness().camera,inspected.camera,'Rejected camera must preserve prior view');
await assert.rejects(api.camera({position:[5,3,7],target:[0,0,0],up:[0,1,0],near:200}),/Camera/,'Near-only edits must validate against retained far');
assert.deepEqual(api.witness().camera,inspected.camera,'Invalid effective clipping pair must preserve prior camera');
assert.equal(api.witness().phase,'interactive','Rejected camera request must not poison the physical runtime');
const firstCamera=api.camera({position:[5,3,7],target:[0,0,0],up:[0,1,0],far:.05});
const followingCamera=api.camera({position:[5,3,7],target:[0,0,0],up:[0,1,0],near:.1});
await firstCamera;const acceptedCamera=api.witness().camera;
await assert.rejects(followingCamera,/Camera/,'Queued partial edits validate against their actual retained predecessor');
assert.deepEqual(api.witness().camera,acceptedCamera);
assert.equal((await api.hold()).clock.presentationDrained,true);
await api.reset();
const reset=await api.hold();
assert.notEqual(reset.clock.runId,first.clock.runId);
assert.equal(reset.clock.completedSteps,30);
assert.equal(reset.clock.experimentSeconds,0);
assert(reset.specimens.every(s=>s.state.hand===null));
