// kaminos-test: node
import assert from 'node:assert/strict';
import * as core from '../burn-fracture-core.mjs';
const {burnJointState}=core;
assert.equal(typeof core.burnInitialJointPenalties,'function','Joint initialization must scale with substep inertia rather than full material stiffness or a unit penalty');
const initial={masses:[2,2],halfExtents:[[1,2,3],[1,2,3]],timeStep:.1,linearStiffness:1e9,rotationalStiffness:1e9,torqueArm:1};
const penalties=core.burnInitialJointPenalties(initial);
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} != ${b}`);
close(penalties.linear,100);
penalties.angular.forEach((v,k)=>close(v,[1300/3,1000/3,500/3][k]));
const faster=core.burnInitialJointPenalties({...initial,timeStep:.05});
close(faster.linear,4*penalties.linear);faster.angular.forEach((v,k)=>close(v,4*penalties.angular[k]));
const anchored=core.burnInitialJointPenalties({...initial,masses:[0,2]});close(anchored.linear,200);
assert.deepEqual(anchored,core.burnInitialJointPenalties({...initial,masses:[2,0]}));
const lever=core.burnInitialJointPenalties({...initial,torqueArm:2});lever.angular.forEach((v,k)=>close(v,penalties.angular[k]/4));
assert.deepEqual(core.burnInitialJointPenalties({...initial,linearStiffness:5,rotationalStiffness:7}),{linear:5,angular:[7,7,7]},'Initialization cannot increase the material stiffness');
for(const change of [{masses:[-1,2]},{masses:[Infinity,2]},{halfExtents:[[0,1,1],[1,1,1]]},{timeStep:0},{torqueArm:0},{linearStiffness:NaN}])assert.throws(()=>core.burnInitialJointPenalties({...initial,...change}));
assert.equal(typeof core.burnMechanicsLocalScale,'function');
const local=core.burnMechanicsLocalScale({cells:[{volume:2}],bonds:[{linearStiffness:100,rotationalStiffness:80}]},.25,{density:500,tension:3000000,compression:12000000,shear:2400000,charStrength:.1});
assert.equal(local.material.density,500*.25**3);assert.equal(local.material.tension,3000000*.25);
assert.equal(local.prepared.bonds[0].linearStiffness,25);assert.equal(local.prepared.bonds[0].rotationalStiffness,20);
assert.equal(local.prepared.cells[0].volume,2,'Local source coordinates do not change');
assert.throws(()=>core.burnMechanicsLocalScale({},0),/scale/);
const bond={id:'cut:0',area:2,linearStiffness:120,rotationalStiffness:80};
const half=burnJointState(bond,{mapped:true,fraction:.5});
assert.equal(half.area,1,'Consumed material must reduce the material area carrying a joint');
assert.equal(half.linearStiffness,60);
assert.equal(half.rotationalStiffness,20,'Bending stiffness scales with the square of remaining area');
assert.equal(burnJointState(bond,{mapped:true,fraction:0}).active,false,'Exhausted sections cannot retain a mechanical constraint');
assert.equal(burnJointState(bond,{mapped:false,fraction:null}).active,true,'Unknown material is not evidence of a break');
assert.equal(burnJointState(bond,{mapped:false,fraction:null}).fraction,null);
for(const fraction of [-1,2,NaN,Infinity,null])assert.throws(()=>burnJointState(bond,{mapped:true,fraction}),/fraction/);
assert.equal(typeof core.createBurnFracturePlayback,'function','Interactive playback needs GPU backpressure instead of an unbounded catch-up burst');
const submitted=[],failures=[];let release;
const playback=core.createBurnFracturePlayback({stepSeconds:1/60,advance:dt=>submitted.push(dt),completed:()=>new Promise(resolve=>{release=resolve;}),onError:e=>failures.push(e)});
playback.tick(1);
assert.deepEqual(submitted,[1/60],'A delayed host frame submits one fixed step');
playback.tick(1);
assert.equal(submitted.length,1,'An outstanding GPU batch must apply backpressure');
assert.ok(Math.abs(playback.read().pendingSeconds-(2-1/60))<1e-12,'All elapsed time is retained');
await Promise.resolve();
release();await playback.settled();
playback.tick(0);assert.equal(submitted.length,2,'Retained work drains after completion without new elapsed time');
await Promise.resolve();
release();await playback.settled();
for(const dt of [-1,NaN,Infinity])assert.throws(()=>playback.tick(dt));
assert.deepEqual(failures,[]);
const failed=core.createBurnFracturePlayback({stepSeconds:1/60,advance(){},completed:()=>Promise.reject(Error('device lost')),onError:e=>failures.push(e.message)});
failed.tick(1/60);await failed.settled();assert.deepEqual(failures,['device lost']);assert.throws(()=>failed.tick(0),/device lost/);
